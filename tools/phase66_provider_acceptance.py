    approved_scope: Literal["unpublished_draft_create_update_only"]
    approved_max_artwork_uploads: StrictInt = Field(ge=0, le=1)
    approved_max_product_posts: StrictInt = Field(ge=0, le=1)
    approved_max_product_puts: StrictInt = Field(ge=0, le=2)
    root_credentials_rejected: Literal[True]
    publication_capability_absent: Literal[True]
    nonce_digest: Digest

    @field_validator(
        "root_credentials_rejected",
        "publication_capability_absent",
        mode="before",
    )
    @classmethod
    def exact_boolean_attestations(cls, value: object) -> object:
        if type(value) is not bool:
            raise ValueError("Provider gate attestations must be exact booleans")
        return value

    @model_validator(mode="after")
    def gate_scope_is_exact(self) -> ProviderGateAuthority:
        if self.gate_id not in _PROVIDER_GATES:
            raise ValueError("Provider gate authority names an unsupported gate")
        issued = _parse_timestamp(self.issued_at)
        expires = _parse_timestamp(self.expires_at)
        if expires <= issued or expires - issued > MAX_AUTHORITY_WINDOW:
            raise ValueError("Provider gate authority window is invalid")
        expected = _EXPECTED_LIMITS[self.gate_id]
        actual = (
            self.approved_max_artwork_uploads,
            self.approved_max_product_posts,
            self.approved_max_product_puts,
        )
        if actual != expected or self.principal_digest != _EXPECTED_CALLER_DIGEST:
            raise ValueError("Provider gate authority scope is not exact")
        return self


