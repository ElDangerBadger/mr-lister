    final_state = (
        ProviderFinalState.UNPUBLISHED_UNLOCKED
        if result.final_product is not None
        else ProviderFinalState.NOT_CREATED
    )
    permit_counts = Counter(permit.status for permit in result.provider_call_permits)
    job_state = (
        result.job.state.value
        if result.job.state in {ControlJobState.APPROVED, ControlJobState.CANCELLED}
        else "nonterminal"
    )
