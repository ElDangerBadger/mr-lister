def _canonical(value: object, *, pretty: bool = False) -> bytes:
    return (
        json.dumps(
            value,
            allow_nan=False,
            ensure_ascii=True,
            indent=2 if pretty else None,
            separators=(",", ": ") if pretty else (",", ":"),
            sort_keys=True,
        )
        + ("\n" if pretty else "")
    ).encode("utf-8")


def _digest(value: object) -> str:
    return sha256(_canonical(value)).hexdigest()


def _parse_timestamp(value: str) -> datetime:
    if type(value) is not str or _TIMESTAMP.fullmatch(value) is None:
        raise ValueError("Timestamp is not canonical UTC RFC3339")
    return datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC)


def _timestamp(value: datetime) -> str:
    if not isinstance(value, datetime) or value.tzinfo is None or value.utcoffset() is None:
        raise ValueError("Timestamp must be timezone-aware")
    return value.astimezone(UTC).replace(microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")


def _strict_json(payload: bytes) -> object:
    def unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        value: dict[str, Any] = {}
        for key, nested in pairs:
            if key in value:
                raise ValueError("Duplicate JSON member")
            value[key] = nested
        return value

    def reject_constant(_value: str) -> None:
        raise ValueError("Non-finite JSON value")

    return json.loads(payload, object_pairs_hook=unique_object, parse_constant=reject_constant)


def _private_path(path: Path) -> Path:
    candidate = Path(os.path.abspath(path))
    try:
        relative = candidate.relative_to(PRIVATE_ROOT)
    except ValueError:
        raise ProviderAcceptanceError(
            "Provider acceptance paths must stay in the repository-private root"
        ) from None
    if not relative.parts:
        raise ProviderAcceptanceError("Provider acceptance path must name one private child")
    return candidate


def _require_private_chain(path: Path, *, create: bool) -> None:
    root = Path(os.path.abspath(REPOSITORY_ROOT))
    current = root
    if not stat.S_ISDIR(root.lstat().st_mode) or stat.S_ISLNK(root.lstat().st_mode):
        raise ProviderAcceptanceError("Repository root is not a stable directory")
    for component in path.relative_to(root).parts:
        current /= component
        try:
            metadata = current.lstat()
        except FileNotFoundError:
            if not create:
                raise ProviderAcceptanceError("Private authority directory is missing") from None
            current.mkdir(mode=0o700)
            metadata = current.lstat()
        if not stat.S_ISDIR(metadata.st_mode) or stat.S_ISLNK(metadata.st_mode):
            raise ProviderAcceptanceError("Private authority path contains a non-directory")
        if metadata.st_mode & 0o077:
            if create:
                current.chmod(0o700)
            else:
                raise ProviderAcceptanceError("Private authority directory is not owner-only")


def _read_private_json(path: Path, expected_sha256: str, label: str) -> object:
    if _DIGEST.fullmatch(expected_sha256) is None:
        raise ProviderAcceptanceError(f"{label} SHA-256 is invalid")
    candidate = _private_path(path)
    _require_private_chain(candidate.parent, create=False)
    try:
        before = candidate.lstat()
        if (
            not stat.S_ISREG(before.st_mode)
            or stat.S_ISLNK(before.st_mode)
            or before.st_nlink != 1
            or before.st_mode & 0o077
            or not 1 <= before.st_size <= MAX_INPUT_BYTES
        ):
            raise OSError
        descriptor = os.open(candidate, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW)
        try:
            chunks: list[bytes] = []
            remaining = before.st_size + 1
            while remaining:
                chunk = os.read(descriptor, min(remaining, 1024 * 1024))
                if not chunk:
                    break
                chunks.append(chunk)
                remaining -= len(chunk)
            payload = b"".join(chunks)
            after = os.fstat(descriptor)
        finally:
            os.close(descriptor)
    except OSError:
        raise ProviderAcceptanceError(
            f"{label} must be one stable mode-0600 private regular file"
        ) from None
    if (
        len(payload) != before.st_size
        or (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns, before.st_ctime_ns)
        != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns)
        or not secrets.compare_digest(sha256(payload).hexdigest(), expected_sha256)
    ):
        raise ProviderAcceptanceError(f"{label} changed or does not match its SHA-256")
    try:
        return _strict_json(payload)
    except (TypeError, UnicodeError, ValueError):
        raise ProviderAcceptanceError(f"{label} is not strict JSON") from None


def _write_private_once(path: Path, payload: bytes) -> str:
    candidate = _private_path(path)
    _require_private_chain(candidate.parent, create=True)
    descriptor: int | None = None
    try:
        descriptor = os.open(
            candidate,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_CLOEXEC | os.O_NOFOLLOW,
            0o600,
        )
        with os.fdopen(descriptor, "wb", closefd=True) as stream:
            descriptor = None
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        candidate.chmod(0o600)
    except OSError:
        raise ProviderAcceptanceError(
            "Provider acceptance output must be fresh and owner-only"
        ) from None
    finally:
        if descriptor is not None:
            os.close(descriptor)
    return sha256(payload).hexdigest()


@contextmanager
def _reserved_private_output(path: Path) -> Iterator[tuple[Path, int]]:
    """Reserve a create-only output before any externally mutating backend can be built."""

    candidate = _private_path(path)
    _require_private_chain(candidate.parent, create=True)
    descriptor: int | None = None
    committed = False
    try:
        descriptor = os.open(
            candidate,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_CLOEXEC | os.O_NOFOLLOW,
            0o600,
        )
        yield candidate, descriptor
        os.fsync(descriptor)
        candidate.chmod(0o600)
        committed = True
    except OSError:
        raise ProviderAcceptanceError(
            "Provider observation output must be fresh and owner-only"
        ) from None
    finally:
        if descriptor is not None:
            opened = os.fstat(descriptor)
            os.close(descriptor)
            if not committed:
                try:
                    current = candidate.lstat()
                    if (opened.st_dev, opened.st_ino) == (current.st_dev, current.st_ino):
                        candidate.unlink()
                except FileNotFoundError:
                    pass


def _deployment_authority(value: object, file_sha256: str) -> _DeploymentAuthority:
    try:
        if not isinstance(value, Mapping) or set(value) != {
            "authority",
            "captured_at",
            "deployment_digest",
            "format",
        }:
            raise ValueError
        authority = value["authority"]
        if not isinstance(authority, Mapping):
            raise ValueError
        deployment_digest = value["deployment_digest"]
        source_digest = authority.get("source_commit_digest")
        if (
            value["format"] != deployment_capture.FORMAT
            or not isinstance(deployment_digest, str)
            or deployment_digest != _digest(authority)
            or not isinstance(source_digest, str)
            or _DIGEST.fullmatch(source_digest) is None
            or authority.get("stack_name") != deployment_capture.EXPECTED_STACK_NAME
            or authority.get("region") != deployment_capture.EXPECTED_REGION
            or authority.get("readiness") != deployment_capture.EXPECTED_READINESS
        ):
            raise ValueError
        lambdas = authority.get("lambdas")
        if not isinstance(lambdas, list):
            raise ValueError
        if len(lambdas) != len(deployment_capture._FUNCTION_LOGICAL_IDS):
            raise ValueError
        logical_ids = {
            record.get("logical_id")
            for record in lambdas
            if isinstance(record, Mapping)
            and set(record)
            == {
                "code_sha256",
                "configuration_digest",
                "last_update_status",
                "logical_id",
                "release_fingerprint_digest",
                "state",
            }
        }
        if logical_ids != set(deployment_capture._FUNCTION_LOGICAL_IDS) or any(
            not isinstance(record, Mapping)
            or any(
                _DIGEST.fullmatch(str(record.get(name))) is None
                for name in (
                    "code_sha256",
                    "configuration_digest",
                    "release_fingerprint_digest",
                )
            )
            or record.get("state") != "Active"
            or record.get("last_update_status") != "Successful"
            for record in lambdas
        ):
            raise ValueError
        expected_release_digest = sha256(
            agentcore_capture.EXPECTED_CLOSURE_RELEASE_FINGERPRINT.encode("ascii")
        ).hexdigest()
        closure = {
            record.get("logical_id"): record
            for record in lambdas
            if isinstance(record, Mapping) and record.get("logical_id") in _CLOSURE_FUNCTIONS
        }
        if set(closure) != _CLOSURE_FUNCTIONS or any(
            record.get("release_fingerprint_digest") != expected_release_digest
            or record.get("state") != "Active"
            or record.get("last_update_status") != "Successful"
            for record in closure.values()
        ):
            raise ValueError
        captured_at = _parse_timestamp(value["captured_at"])
    except (KeyError, TypeError, ValueError):
        raise ProviderAcceptanceError(
            "Deployment authority does not bind the exact artwork-closure runtime"
        ) from None
    return _DeploymentAuthority(
        digest=deployment_digest,
        file_sha256=file_sha256,
        source_commit_digest=source_digest,
        captured_at=captured_at,
    )


def _agentcore_authority(value: object, file_sha256: str) -> _AgentCoreAuthority:
    try:
        if not isinstance(value, Mapping):
            raise ValueError
        agentcore_capture._validate_document(value)
        authority_digest = value.get("authority_digest")
        if not isinstance(authority_digest, str):
            raise ValueError
        captured_at = _parse_timestamp(value["captured_at"])
    except (KeyError, TypeError, ValueError):
        raise ProviderAcceptanceError(
            "AgentCore authority does not bind the exact artwork-closure runtime"
        ) from None
    return _AgentCoreAuthority(
        digest=authority_digest,
        file_sha256=file_sha256,
        captured_at=captured_at,
    )


def _prerequisites(
    value: object,
    *,
    gate_id: str,
    deployment: _DeploymentAuthority,
) -> tuple[Any, ...]:
    if not isinstance(value, list):
        raise ProviderAcceptanceError("Provider prerequisites must be one evidence-record array")
    gate = next(item for item in phase66_acceptance_manifest().gates if item.gate_id == gate_id)
    expected = gate.prerequisites
    records: list[Any] = []
    try:
        for nested in value:
            record = validate_phase66_evidence(nested)
            if (
                record.outcome is not AcceptanceOutcome.PASSED
                or getattr(record, "deployment_digest", None) != deployment.digest
                or record.source_commit_digest != deployment.source_commit_digest
            ):
                raise ValueError
            records.append(record)
    except (TypeError, ValueError):
        raise ProviderAcceptanceError(
            "Provider prerequisites do not bind the passed deployment/source"
        ) from None
    by_gate = {record.gate_id: record for record in records}
    if (
        len(by_gate) != len(records)
        or set(by_gate) != set(expected)
        or any(record.recorded_at < deployment.captured_at for record in records)
    ):
        raise ProviderAcceptanceError("Provider prerequisites are not the exact frozen gate set")
    return tuple(by_gate[gate_name] for gate_name in expected)


def _gate_authority(value: object, label: str) -> ProviderGateAuthority:
    try:
        return ProviderGateAuthority.model_validate(value)
    except (TypeError, ValidationError, ValueError):
        raise ProviderAcceptanceError(
            f"{label} does not match the closed authority contract"
        ) from None


def _load_authority_bundle(
    *,
    gate_id: str,
    deployment_authority_path: Path,
    deployment_authority_sha256: str,
    agentcore_authority_path: Path,
    agentcore_authority_sha256: str,
    prerequisite_records_path: Path,
    prerequisite_records_sha256: str,
    run_gate_path: Path,
    run_gate_sha256: str,
    provider_write_gate_path: Path,
    provider_write_gate_sha256: str,
) -> _AuthorityBundle:
    if gate_id not in _PROVIDER_GATES:
        raise ProviderAcceptanceError("Provider gate is not one frozen Phase 6.6 gate")
    paths = (
        deployment_authority_path,
        agentcore_authority_path,
        prerequisite_records_path,
        run_gate_path,
        provider_write_gate_path,
    )
    if len({_private_path(path) for path in paths}) != len(paths):
        raise ProviderAcceptanceError("Provider authority inputs must be distinct files")
    deployment = _deployment_authority(
        _read_private_json(
            deployment_authority_path,
            deployment_authority_sha256,
            "deployment authority",
        ),
        deployment_authority_sha256,
    )
    agentcore = _agentcore_authority(
        _read_private_json(
            agentcore_authority_path,
            agentcore_authority_sha256,
            "AgentCore authority",
        ),
        agentcore_authority_sha256,
    )
    prerequisites = _prerequisites(
        _read_private_json(
            prerequisite_records_path,
            prerequisite_records_sha256,
            "prerequisite records",
        ),
        gate_id=gate_id,
        deployment=deployment,
    )
    run_gate = _gate_authority(
        _read_private_json(run_gate_path, run_gate_sha256, "run gate"),
        "run gate",
    )
    write_gate = _gate_authority(
        _read_private_json(
            provider_write_gate_path,
            provider_write_gate_sha256,
            "provider write gate",
        ),
        "provider write gate",
    )
    prerequisite_digests = tuple(record.run_digest for record in prerequisites)
    common = {
        "gate_id": gate_id,
        "deployment_digest": deployment.digest,
        "deployment_authority_sha256": deployment.file_sha256,
        "agentcore_authority_digest": agentcore.digest,
        "agentcore_authority_sha256": agentcore.file_sha256,
        "source_commit_digest": deployment.source_commit_digest,
        "principal_digest": _EXPECTED_CALLER_DIGEST,
        "prerequisite_run_digests": list(prerequisite_digests),
    }
    for authority, kind in (
        (run_gate, ProviderGateKind.RUN),
        (write_gate, ProviderGateKind.WRITE),
    ):
        rendered = authority.model_dump(mode="json")
        if authority.gate_kind is not kind or any(
            rendered[name] != expected for name, expected in common.items()
        ):
            raise ProviderAcceptanceError("Provider gates do not bind one exact authority set")
        issued = _parse_timestamp(authority.issued_at)
        if issued < max(
            deployment.captured_at,
            agentcore.captured_at,
            *(record.recorded_at for record in prerequisites),
        ):
            raise ProviderAcceptanceError("Provider gate predates a required authority")
    if (
        run_gate_sha256 == provider_write_gate_sha256
        or run_gate.nonce_digest == write_gate.nonce_digest
        or (run_gate.issued_at, run_gate.expires_at)
        != (write_gate.issued_at, write_gate.expires_at)
        or run_gate.model_dump(mode="json", exclude={"gate_kind", "nonce_digest"})
        != write_gate.model_dump(mode="json", exclude={"gate_kind", "nonce_digest"})
    ):
        raise ProviderAcceptanceError("Provider run and write gates are not independent peers")
    run_digest = _digest(
        {
            "contract": "phase6.6-provider-canary-run-v1",
            "gate_id": gate_id,
            "deployment_digest": deployment.digest,
            "agentcore_authority_digest": agentcore.digest,
            "source_commit_digest": deployment.source_commit_digest,
            "run_gate_digest": run_gate_sha256,
            "provider_write_gate_digest": provider_write_gate_sha256,
            "prerequisite_run_digests": prerequisite_digests,
        }
    )
    return _AuthorityBundle(
        gate_id=gate_id,
        deployment=deployment,
        agentcore=agentcore,
        run_gate=run_gate,
        run_gate_digest=run_gate_sha256,
        write_gate=write_gate,
        write_gate_digest=provider_write_gate_sha256,
        prerequisite_records=prerequisites,
        run_digest=run_digest,
    )


def _call_counts(calls: Sequence[Any]) -> dict[str, int]:
    normalized = tuple(
        (
            call.audit.method if isinstance(call, ProviderLiveCall) else call.method,
            call.audit.path if isinstance(call, ProviderLiveCall) else call.path,
        )
        for call in calls
    )
    return {
        "artwork": sum(
            method == "POST" and path == "/v1/uploads/images.json" for method, path in normalized
        ),
        "post": sum(
            method == "POST" and path == "/v1/shops/{shop_id}/products.json"
            for method, path in normalized
        ),
        "put": sum(
            method == "PUT" and path == "/v1/shops/{shop_id}/products/{product_id}.json"
            for method, path in normalized
        ),
        "get": sum(
            method == "GET" and path == "/v1/shops/{shop_id}/products/{product_id}.json"
            for method, path in normalized
        ),
    }


def _active_work_count(work_requests: Sequence[WorkRequest]) -> int:
    return sum(
        work.status
        in {WorkRequestStatus.PENDING, WorkRequestStatus.CLAIMED, WorkRequestStatus.DISPATCHED}
        for work in work_requests
    )


def _analysis_is_valid(result: ProviderLiveResult) -> bool:
    analysis = result.artwork_analysis
    if analysis is None:
        return False
    material = {
        "job_id": analysis.job_id,
        "source_artifact_fingerprint": analysis.source_artifact_fingerprint,
        "analysis": analysis.analysis.model_dump(mode="json"),
    }
    return (
        analysis.job_id == result.job.job_id
        and analysis.analysis_id == result.job.artwork_analysis_id
        and analysis.fingerprint == result.job.artwork_analysis_fingerprint
        and analysis.source_artifact_fingerprint == result.job.source_artifact_fingerprint
        and analysis.fingerprint == canonical_fingerprint(material)
        and result.agent_evidence is not None
        and analysis.work_request_id == result.agent_evidence.work_request_id
        and analysis.work_request_id in {work.work_request_id for work in result.work_requests}
    )


def _agent_is_valid(result: ProviderLiveResult) -> bool:
    evidence = result.agent_evidence
    return bool(
        evidence is not None
        and evidence.job_id == result.job.job_id
        and evidence.evidence_id == result.job.agent_evidence_id
        and evidence.fingerprint == result.job.agent_evidence_fingerprint
        and evidence.fingerprint == evidence.authority_fingerprint
        and evidence.controller_model_id
        == agentcore_capture._expected_runtime_environment()[
            "MR_LISTER_STRANDS_CONTROLLER_MODEL_ID"
        ]
        and evidence.work_request_id
        in {
            work.work_request_id
            for work in result.work_requests
            if work.work_type is WorkType.PREPARE
        }
        and evidence.correlation_id == result.agentcore_correlation_id
        and evidence.publication_authorized is False
    )


def _sync_is_valid(result: ProviderLiveResult) -> bool:
    sync = result.product_sync
    return bool(
        sync is not None
        and sync.job_id == result.job.job_id
        and sync.sync_id == result.job.product_sync_id
        and sync.product_id == result.job.product_id
        and sync.image_id == result.job.uploaded_image_id
        and sync.review_version == result.job.synchronized_review_version
        and sync.payload_fingerprint == result.job.provider_payload_fingerprint
        and sync.fingerprint == result.job.product_sync_fingerprint
        and sync.fingerprint == product_sync_record_fingerprint(sync)
        and not sync.provider_locked
        and not sync.provider_published
    )


def _source_is_valid(result: ProviderLiveResult) -> bool:
    source = result.source_artifact
    return bool(
        source is not None
        and source.job_id == result.job.job_id
        and source.owner_id == result.job.owner_id
        and source.fingerprint == result.job.source_artifact_fingerprint
        and source.size_bytes == result.source_size_bytes
    )


def _validate_command_evidence(
    result: ProviderLiveResult,
    *,
    expected: ProviderCommandName,
) -> None:
    receipts = {receipt.receipt_id: receipt for receipt in result.command_receipts}
    decisions: tuple[ReviewDecisionRecord | CancellationDecisionRecord, ...] = (
        *result.review_decisions,
        *result.cancellation_decisions,
    )
    if (
        len(receipts) != 1
        or len(result.command_receipts) != 1
        or len(decisions) != 1
        or any(
            receipt.owner_id != result.job.owner_id
            or receipt.job_id != result.job.job_id
            or receipt.response.job_id != result.job.job_id
            or (
                receipt.work_request_id is not None
                and receipt.work_request_id
                not in {work.work_request_id for work in result.work_requests}
            )
            for receipt in result.command_receipts
        )
        or any(
            decision.job_id != result.job.job_id
            or decision.actor_owner_id != result.job.owner_id
            or decision.command_receipt_id not in receipts
            for decision in decisions
        )
    ):
        raise ProviderAcceptanceError("Provider command lacks one durable seller decision")
    decision = decisions[0]
    receipt = receipts[decision.command_receipt_id]
    if expected is ProviderCommandName.CANCEL:
        valid = (
            isinstance(decision, CancellationDecisionRecord)
            and not result.review_decisions
            and receipt.command_type == "cancel_job"
            and receipt.response.state is ControlJobState.CANCELLED
            and receipt.work_request_id is None
            and (
                not result.command_outcomes
                or decision.expected_record_version
                == next(
                    command.expected_record_version
                    for command in result.command_outcomes
                    if command.outcome is ProviderCommandOutcome.WON
                )
            )
        )
    else:
        review_decision = (
            ReviewDecision.REVISE
            if expected is ProviderCommandName.REVISE
            else ReviewDecision.APPROVE
        )
        command_type = (
            "revise_listing" if expected is ProviderCommandName.REVISE else "approve_review"
        )
        valid = (
            isinstance(decision, ReviewDecisionRecord)
            and not result.cancellation_decisions
            and decision.decision is review_decision
            and receipt.command_type == command_type
            and (
                review_decision is not ReviewDecision.APPROVE
                or (
                    receipt.response.state is ControlJobState.APPROVED
                    and receipt.work_request_id is None
                    and decision.decision_id == result.job.approval_decision_id
                    and decision.review_version == result.job.review_version
                    and decision.review_fingerprint == result.job.review_fingerprint
                    and decision.approval_fingerprint == result.job.approval_fingerprint
                )
            )
        )
    if not valid:
        raise ProviderAcceptanceError("Provider command decision changed the winning operation")


def _validate_live_result(result: ProviderLiveResult, authority: _AuthorityBundle) -> None:
    if result.gate_id != authority.gate_id:
        raise ProviderAcceptanceError("Live provider result changed the authorized gate")
    observed = result.observed_at.astimezone(UTC)
    if not (
        _parse_timestamp(authority.run_gate.issued_at)
        <= observed
        <= _parse_timestamp(authority.run_gate.expires_at)
    ):
        raise ProviderAcceptanceError("Live provider result is outside its exact gate window")
    if (
        result.aws_caller_arn != agentcore_capture.EXPECTED_CALLER_ARN
        or result.aws_caller_arn.endswith(":root")
        or result.seller_actor_owner_id != result.job.owner_id
        or not result.seller_command_channel
        or result.root_action_count
        or result.administrator_action_count
        or result.publication_attempt_count
        or result.order_attempt_count
        or result.fulfillment_attempt_count
        or result.job.publication_aggregate_id is not None
        or result.job.publication_terminal_state is not None
        or result.job.publication_result_id is not None
    ):
        raise ProviderAcceptanceError("Live provider result crossed the Phase 6 authority boundary")
    if tuple(call.ordinal for call in result.provider_calls) != tuple(
        range(1, len(result.provider_calls) + 1)
    ):
        raise ProviderAcceptanceError("Provider call ledger is not one exact ordered sequence")
    work_ids = {work.work_request_id for work in result.work_requests}
    if len(work_ids) != len(result.work_requests) or any(
        work.job_id != result.job.job_id or work.owner_id != result.job.owner_id
        for work in result.work_requests
    ):
        raise ProviderAcceptanceError("Durable work inventory changed job or seller authority")
    permits = {permit.attempt_id: permit for permit in result.provider_call_permits}
    if len(permits) != len(result.provider_call_permits) or any(
        permit.job_id != result.job.job_id or permit.work_request_id not in work_ids
        for permit in result.provider_call_permits
    ):
        raise ProviderAcceptanceError("Provider permit inventory changed job authority")
    mutation_calls = [
        call for call in result.provider_calls if call.audit.method in {"POST", "PUT"}
    ]
    mutation_attempts = {call.attempt_id for call in mutation_calls}
    if len(mutation_attempts) != len(mutation_calls):
        raise ProviderAcceptanceError("Provider mutation reused one call permit")
    for call in mutation_calls:
        permit = permits.get(call.attempt_id)
        if (
            permit is None
            or permit.status is not ProviderCallPermitStatus.CONSUMED
            or permit.work_request_id != call.work_request_id
            or permit.consumed_work_request_id != call.work_request_id
            or call.work_request_id not in work_ids
        ):
            raise ProviderAcceptanceError("Provider mutation lacks one consumed durable permit")
    if any(
        permit.status is ProviderCallPermitStatus.CONSUMED
        and permit.attempt_id not in mutation_attempts
        for permit in result.provider_call_permits
    ):
        raise ProviderAcceptanceError("Consumed provider permit lacks one audited mutation")
    counts = _call_counts(result.provider_calls)
    limits = _EXPECTED_LIMITS[result.gate_id]
    if counts["artwork"] > limits[0] or counts["post"] > limits[1] or counts["put"] > limits[2]:
        raise ProviderAcceptanceError("Provider call ledger exceeds its exact write gate")
    if counts["artwork"]:
        if not _source_is_valid(result):
            raise ProviderAcceptanceError("Artwork upload lacks one exact durable source")
    elif result.source_artifact is not None or result.source_size_bytes is not None:
        raise ProviderAcceptanceError("Durable source lacks an audited artwork upload")

    if result.gate_id == "provider.primary_same_job_canary":
        _validate_primary(result, counts)
    elif result.gate_id == "provider.concurrency_canary":
        _validate_concurrency(result, counts)
    else:
        _validate_cancellation(result, counts)


def _validate_product_join(result: ProviderLiveResult, *, require_final_get: bool) -> None:
    sync = result.product_sync
    final = result.final_product
    if not _sync_is_valid(result) or sync is None or final is None:
        raise ProviderAcceptanceError("Provider product evidence is not one durable safe draft")
    product_calls = [call for call in result.provider_calls if call.product_id is not None]
    if (
        not product_calls
        or any(call.product_id != sync.product_id for call in product_calls)
        or final.product_id != sync.product_id
        or final.payload_fingerprint != sync.payload_fingerprint
        or (require_final_get and product_calls[-1].audit.method != "GET")
    ):
        raise ProviderAcceptanceError("Provider calls do not bind one final unpublished product")


def _validate_primary(result: ProviderLiveResult, counts: Mapping[str, int]) -> None:
    if (
        result.source_size_bytes != PRIMARY_SOURCE_BYTES
        or result.job.state is not ControlJobState.APPROVED
        or result.job.active_work_request_id is not None
        or result.gemma_inference_count != 1
        or not _analysis_is_valid(result)
        or not _agent_is_valid(result)
        or counts["artwork"] != 1
        or counts["post"] != 1
        or counts["put"] != 2
        or counts["get"] < 1
        or result.command_outcomes
        or result.running_execution_count
        or any(
            permit.status is ProviderCallPermitStatus.AVAILABLE
            for permit in result.provider_call_permits
        )
        or _active_work_count(result.work_requests)
    ):
        raise ProviderAcceptanceError(
            "Primary provider canary did not prove the exact same-job flow"
        )
    _validate_command_evidence(result, expected=ProviderCommandName.APPROVE)
    if result.review_decisions[0].decision_id != result.job.approval_decision_id:
        raise ProviderAcceptanceError("Primary approval decision changed durable authority")
    _validate_product_join(result, require_final_get=True)


def _validate_concurrency(result: ProviderLiveResult, counts: Mapping[str, int]) -> None:
    names = tuple(command.name for command in result.command_outcomes)
    versions = {command.expected_record_version for command in result.command_outcomes}
    if (
        len(result.command_outcomes) != 3
        or set(names) != set(ProviderCommandName)
        or len(set(names)) != 3
        or len(versions) != 1
        or sum(command.outcome is ProviderCommandOutcome.WON for command in result.command_outcomes)
        != 1
        or any(command.actor_owner_id != result.job.owner_id for command in result.command_outcomes)
        or counts["put"] > 1
        or result.running_execution_count
        or any(
            permit.status is ProviderCallPermitStatus.AVAILABLE
            for permit in result.provider_call_permits
        )
    ):
        raise ProviderAcceptanceError("Concurrency canary did not prove one three-command winner")
    winner = next(
        command.name
        for command in result.command_outcomes
        if command.outcome is ProviderCommandOutcome.WON
    )
    _validate_command_evidence(result, expected=winner)
    if any(call.product_id is not None for call in result.provider_calls):
        _validate_product_join(result, require_final_get=bool(counts["get"]))
    elif result.product_sync is not None or result.final_product is not None:
        raise ProviderAcceptanceError("Concurrency product evidence lacks an audited product call")


def _validate_cancellation(result: ProviderLiveResult, counts: Mapping[str, int]) -> None:
    if (
        result.job.state is not ControlJobState.CANCELLED
        or result.job.active_work_request_id is not None
        or counts != {"artwork": 0, "post": 0, "put": 0, "get": 0}
        or result.provider_calls
        or result.product_sync is not None
        or result.final_product is not None
        or result.source_size_bytes is not None
        or result.artwork_analysis is not None
        or result.agent_evidence is not None
        or result.agentcore_correlation_id is not None
        or result.gemma_inference_count
        or result.running_execution_count
        or _active_work_count(result.work_requests)
        or len(result.command_outcomes) != 1
        or result.command_outcomes[0].name is not ProviderCommandName.CANCEL
        or result.command_outcomes[0].outcome is not ProviderCommandOutcome.WON
        or result.command_outcomes[0].actor_owner_id != result.job.owner_id
        or any(
            permit.status is ProviderCallPermitStatus.AVAILABLE
            for permit in result.provider_call_permits
        )
    ):
        raise ProviderAcceptanceError(
            "Cancellation canary did not prove seller-only terminal cancellation"
        )
    _validate_command_evidence(result, expected=ProviderCommandName.CANCEL)


def _derived_digest(run_digest: str, kind: str, raw_value: str) -> str:
    return sha256(
        b"\0".join(
            (b"phase6.6-provider-id-v1", run_digest.encode(), kind.encode(), raw_value.encode())
        )
    ).hexdigest()


def _sanitize_result(result: ProviderLiveResult, authority: _AuthorityBundle) -> dict[str, object]:
    _validate_live_result(result, authority)
    actor_digest = _derived_digest(authority.run_digest, "actor", result.job.owner_id)
    job_digest = _derived_digest(authority.run_digest, "job", result.job.job_id)
    primary = result.gate_id == "provider.primary_same_job_canary"
    work_digest = (
        _derived_digest(authority.run_digest, "work", result.agent_evidence.work_request_id)
        if primary and result.agent_evidence is not None
        else None
    )
    correlation_digest = (
        _derived_digest(authority.run_digest, "correlation", result.agentcore_correlation_id)
        if primary and result.agentcore_correlation_id is not None
        else None
    )
    calls = []
    for call in result.provider_calls:
        calls.append(
            {
                "ordinal": call.ordinal,
                "method": call.audit.method,
                "path": call.audit.path,
                "status_code": call.status_code,
                "attempt_digest": (
                    _derived_digest(authority.run_digest, "attempt", call.attempt_id)
                    if call.attempt_id is not None
                    else None
                ),
                "work_digest": (
                    _derived_digest(authority.run_digest, "work", call.work_request_id)
                    if call.work_request_id is not None
                    else None
                ),
                "product_digest": (
                    _derived_digest(authority.run_digest, "product", call.product_id)
                    if call.product_id is not None
                    else None
                ),
            }
        )
    call_models = tuple(SanitizedProviderCall.model_validate(call) for call in calls)
    decision_digest = (
        _digest(
            {
                "contract": "phase6.6-provider-decision-v1",
                "run_digest": authority.run_digest,
                "decision": (
                    (*result.review_decisions, *result.cancellation_decisions)[0].model_dump(
                        mode="json"
                    )
                ),
            }
        )
        if result.command_outcomes
        else None
    )
    command_models = tuple(
        SanitizedCommandObservation(
            name=command.name,
            outcome=command.outcome,
            actor_digest=actor_digest,
            expected_record_version=command.expected_record_version,
            decision_digest=(
                decision_digest if command.outcome is ProviderCommandOutcome.WON else None
            ),
        )
        for command in result.command_outcomes
    )
